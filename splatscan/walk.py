"""A person walking a loop through the lab with a head-mounted camera + IMU.

The trajectory plugs straight into ``insight_vio.sim.simulate`` (which needs analytic
position / velocity / acceleration and a rotation), so the IMU stream is generated by
insight-vio's own simulator - with its noise model, bias random walk and exact zero-order-hold
consistency - and the images come from :class:`splatscan.room.LabRoom`.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np


def _rot_zyx(yaw, pitch, roll):
    cy, sy, cp, sp, cr, sr = np.cos(yaw), np.sin(yaw), np.cos(pitch), np.sin(pitch), np.cos(roll), np.sin(roll)
    Rz = np.array([[cy, -sy, 0], [sy, cy, 0], [0, 0, 1]])
    Ry = np.array([[cp, 0, sp], [0, 1, 0], [-sp, 0, cp]])
    Rx = np.array([[1, 0, 0], [0, cr, -sr], [0, sr, cr]])
    return Rz @ Ry @ Rx


@dataclass
class LabWalk:
    """Elliptical loop (rx x ry metres) walked counter-clockwise in ``period`` seconds.

    The head faces mostly outwards (towards the walls and furniture), sweeping left/right,
    with a walking bob and small pitch/roll nods. The walk starts slowly (smoothstep ramp
    over ``ramp`` seconds) so the filter sees a gentle start.
    """
    rx: float = 1.9
    ry: float = 1.5
    period: float = 34.0
    height: float = 1.55
    ramp: float = 3.0
    yaw_offset: float = 0.35
    sweep: float = 0.45

    def _phase(self, t):
        """phi(t) and its first two derivatives: smooth start, then constant angular speed."""
        w = 2 * np.pi / self.period
        T = self.ramp
        if t < T:
            s = t / T
            # integral of smoothstep ramp: phi = w*T*(s^3 - s^4/2), phi' = w*(3s^2 - 2s^3)
            return w * T * (s ** 3 - 0.5 * s ** 4), w * (3 * s ** 2 - 2 * s ** 3), w * (6 * s - 6 * s ** 2) / T
        return w * T * 0.5 + w * (t - T), w, 0.0

    def position(self, t):
        ph, _, _ = self._phase(t)
        bob = 0.025 * np.sin(2 * np.pi * 1.8 * t) * self._gain(t)
        return np.array([self.rx * np.cos(ph), self.ry * np.sin(ph), self.height + bob])

    def _gain(self, t):
        return min(1.0, t / self.ramp) ** 2 if self.ramp > 0 else 1.0

    def velocity(self, t, h=1e-4):
        return (self.position(t + h) - self.position(t - h)) / (2 * h)

    def acceleration(self, t, h=1e-3):
        return (self.position(t + h) - 2 * self.position(t) + self.position(t - h)) / (h * h)

    def rotation(self, t):
        ph, _, _ = self._phase(t)
        yaw = ph + self.yaw_offset + self.sweep * np.sin(0.45 * t) * self._gain(t)
        pitch = 0.12 + 0.08 * np.sin(0.7 * t + 0.3)
        roll = 0.03 * np.sin(2 * np.pi * 0.9 * t)
        return _rot_zyx(yaw, pitch, roll)
